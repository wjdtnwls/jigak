# ──────────────────────────────────────────────────────────────
# 예상 택시비 계산
#
# 요금 기준: 부산 중형택시, 2023년 6월 1일 인상분 (기본 4,800원 / 2km, 이후 132m당 100원).
# 요금이 다시 바뀌었다면 아래 숫자만 고치면 돼요. 심야 할증과 시간대별 교통 상황은 반영하지 않아요.
# ──────────────────────────────────────────────────────────────
BASE_FARE = 4800        # 기본요금(원)
BASE_METERS = 2000      # 기본요금에 포함된 거리(m)
STEP_METERS = 132       # 이후 이 거리마다
STEP_WON = 100          # 이 금액이 추가
ROAD_FACTOR = 1.35      # 직선거리 -> 실제 도로 거리 보정 (도심은 보통 1.3~1.4배)
TRAFFIC_FACTOR = 1.08   # 신호 대기 등 시간요금 여유


def _haversine_km(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(h))


def estimate_fare(origin, dest):
    """출발역 -> 대학 예상 택시비. 좌표가 없으면 None."""
    a, b = STATION_XY.get(origin), UNIVERSITY_XY.get(dest)
    if not a or not b:
        return None
    road_km = max(_haversine_km(a, b) * ROAD_FACTOR, 0.5)
    meters = road_km * 1000
    fare = BASE_FARE + max(0.0, meters - BASE_METERS) / STEP_METERS * STEP_WON
    fare = fare * TRAFFIC_FACTOR
    to100 = lambda x: int(round(x / 100.0)) * 100
    return {
        "km": round(road_km, 1),
        "fare": to100(fare),
        "low": to100(fare * 0.9),
        "high": to100(fare * 1.2),
    }
